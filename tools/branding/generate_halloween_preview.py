"""Render the Halloween design proof and pack the local native vector wallpaper.

This is a palette/artwork proof, not a simulator screenshot. Icon production slots
are generated by generate_icons.py; the wallpaper SVG is its editable master.
"""
import argparse
import gzip
import io
from pathlib import Path
import cairosvg
from PIL import Image, ImageDraw, ImageFont
from generate_icons import render

ROOT = Path(__file__).resolve().parents[2]


def generate(output):
    master = (ROOT/'assets/branding/HalloweenWallpaper.svg').read_bytes()
    packed = gzip.compress(master, mtime=0)
    (ROOT/'submodules/TelegramUI/Resources/bananagram-halloween-v1.tgv').write_bytes(packed)
    image = Image.new('RGB', (1560, 1180), '#100E16')
    draw = ImageDraw.Draw(image)
    fonts = [Path('C:/Windows/Fonts/segoeui.ttf'), Path('/System/Library/Fonts/Supplemental/Arial.ttf'), Path('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf')]
    font = next((str(path) for path in fonts if path.exists()), None)
    def text(x, y, value, size=24, color='#F8F0E8'):
        face = ImageFont.truetype(font, size) if font else ImageFont.load_default(size=size)
        draw.text((x, y), value, font=face, fill=color)
    text(72, 48, 'BananaGram / Halloween', 45)
    text(74, 112, 'Midnight violet. Pumpkin light.', 25, '#C0B2CB')
    # Chat proof: use the exact vector master at the phone's aspect ratio.
    x, y, w, h = 72, 194, 440, 906
    draw.rounded_rectangle((x-3, y-3, x+w+3, y+h+3), radius=43, fill='#3A3049')
    draw.rounded_rectangle((x, y, x+w, y+h), radius=40, fill='#1E1929')
    tile = master.replace(b'fill="#000"', b'fill="#71567E"')
    pattern = Image.open(io.BytesIO(cairosvg.svg2png(bytestring=tile, output_width=w, output_height=h))).convert('RGBA')
    backdrop = Image.new('RGBA', (w, h), '#1A1425')
    pattern.putalpha(pattern.getchannel('A').point(lambda a: round(a*.22)))
    backdrop.alpha_composite(pattern)
    image.paste(backdrop.convert('RGB'), (x, y))
    draw.rounded_rectangle((x, y, x+w, y+113), radius=32, fill='#1E1929')
    draw.rectangle((x, y+65, x+w, y+113), fill='#1E1929')
    text(x+24, y+16, '9:41', 18)
    text(x+22, y+58, '‹', 34, '#FFB45E')
    text(x+73, y+55, 'Halloween night', 24)
    text(x+73, y+86, 'online', 16, '#C0B2CB')
    for bx, by, bw, bh, fill, lines in [
        (x+16,y+211,326,110,'#2A2338',['The lights are on.', 'The night is ours.']),
        (x+104,y+351,320,111,'#543326',['Meet me at midnight.', 'Bring the pumpkins.']),
        (x+16,y+498,331,151,'#2A2338',['A little magic,', 'a warm glow,', 'one very dark theme.']),
    ]:
        draw.rounded_rectangle((bx,by,bx+bw,by+bh),radius=23,fill=fill)
        for i,line in enumerate(lines):text(bx+17,by+15+i*31,line,21)
        text(bx+bw-59,by+bh-25,'00:31',13,'#C0B2CB')
    draw.rounded_rectangle((x+32,y+661,x+124,y+703),radius=20,fill='#FFB45E')
    text(x+51,y+666,'♥  3',20,'#24150D')
    draw.rectangle((x,y+h-85,x+w,y+h),fill='#1E1929')
    draw.rounded_rectangle((x+16,y+h-69,x+w-73,y+h-15),radius=24,fill='#2A2338',outline='#3A3049')
    text(x+35,y+h-60,'Message',22,'#C0B2CB')
    draw.ellipse((x+w-62,y+h-66,x+w-14,y+h-18),fill='#FFB45E')
    draw.polygon([(x+w-49,y+h-49),(x+w-25,y+h-43),(x+w-49,y+h-34)],fill='#24150D')
    text(581,200,'The Halloween icon',30)
    icon = render('HalloweenIcon',(284,284))
    mask = Image.new('L',icon.size);ImageDraw.Draw(mask).rounded_rectangle((0,0,283,283),radius=64,fill=255)
    image.paste(icon,(582,255),mask)
    text(582,572,'Readable at launcher size',23,'#C0B2CB')
    for dx,size in [(0,60),(88,40),(158,29)]:
        image.paste(render('HalloweenIcon',(size,size)),(582+dx,626+60-size))
        text(582+dx,703,str(size)+' px',16,'#C0B2CB')
    text(983,200,'A complete dark palette',30)
    for i,(label,color) in enumerate([('Midnight','#14111D'),('Surface','#1E1929'),('Raised','#2A2338'),('Pumpkin','#FFB45E'),('Moonlight','#F8F0E8'),('Muted lilac','#C0B2CB')]):
        by=269+i*81
        draw.rounded_rectangle((984,by,1050,by+58),radius=14,fill=color,outline='#3A3049')
        text(1073,by+1,label,22)
        text(1073,by+31,color.upper(),17,'#C0B2CB')
    text(582,827,'Built into the theme',28)
    text(582,879,'Chats · lists · menus · keyboard panels',23,'#C0B2CB')
    text(582,919,'Calls · passcode · badges · reactions',23,'#C0B2CB')
    text(582,959,'Original vector wallpaper. Available offline.',23,'#C0B2CB')
    text(582,1051,'Design proof / artwork and palette, not a device screenshot',17,'#9784A6')
    # Clip the complete chat proof, including the pattern and composer, to its rounded frame.
    phone = image.crop((x,y,x+w,y+h))
    phone_mask = Image.new('L',(w,h))
    ImageDraw.Draw(phone_mask).rounded_rectangle((0,0,w-1,h-1),radius=40,fill=255)
    draw.rectangle((x,y,x+w,y+h),fill='#100E16')
    image.paste(phone,(x,y),phone_mask)
    output.parent.mkdir(parents=True,exist_ok=True)
    image.save(output,optimize=True)
    print(f'Wrote {output}; native wallpaper {len(packed)} bytes')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--output',type=Path,default=ROOT/'assets/branding/HalloweenPreview.png')
    generate(parser.parse_args().output)
